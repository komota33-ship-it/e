export function sectorPanel(zone, index, ground) {
  const sheet = SHEETS[zone],
    row = Math.floor(index / 2),
    top = sheet.rows[row];
  const height = sheet.rows[row + 1] - top,
    scale = ground / (sheet.grounds[index] - top);
  const width = 543 * scale,
    rect = sheet.loot[index];
  return {
    art: `sector_${zone}`,
    lootLabel: CONTAINER_LABELS[zone][index],
    index,
    panel: true,
    source: [(index % 2) * 543, top, 543, height],
    width,
    height: height * scale,
    lootRect: [
      rect[0] * width,
      rect[1] * height * scale,
      rect[2] * width,
      rect[3] * height * scale,
    ],
  };
}
