const byFloor = new Map(JOURNAL_NOTES.map((note) => [note.floor, note]));
const byId = new Map(JOURNAL_NOTES.map((note) => [note.id, note]));

export const noteForFloor = (floor) => byFloor.get(floor) || null;
export const noteForId = (id) => byId.get(id) || null;

export function normalizeJournal(value) {
  if (!Array.isArray(value)) return [];
  return [
    ...new Set(value.filter((id) => typeof id === "string" && byId.has(id))),
  ];
}

export function readJournal(storage) {
  try {
    return normalizeJournal(JSON.parse(storage.getItem(JOURNAL_KEY)));
  } catch {
    return [];
  }
}

export function writeJournal(storage, ids) {
  try {
    storage.setItem(JOURNAL_KEY, JSON.stringify(normalizeJournal(ids)));
    return true;
  } catch {
    return false;
  }
}
