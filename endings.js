export const ENDING_IDS = Object.keys(ENDINGS);

export function normalizeEndings(value) {
  if (!Array.isArray(value)) return [];
  return [
    ...new Set(
      value.filter(
        (id) => typeof id === "string" && Object.hasOwn(ENDINGS, id),
      ),
    ),
  ];
}

export function readEndings(storage) {
  try {
    return normalizeEndings(JSON.parse(storage.getItem(ENDINGS_KEY)));
  } catch {
    return [];
  }
}

export function writeEndings(storage, ids) {
  try {
    storage.setItem(ENDINGS_KEY, JSON.stringify(normalizeEndings(ids)));
    return true;
  } catch {
    return false;
  }
}
